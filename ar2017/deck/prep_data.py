"""Precompute everything the deck shows into deck/public/deck_data.json and inline it into deck.py.

The deck never estimates anything live: every number comes from the validated pipeline outputs
(results/*.csv) or from the raw files used by that pipeline. Inlining the JSON into the notebook keeps
every export path self-contained (marimo run, static HTML, WASM).

Run from the project root after ./run_all.sh:   python3 deck/prep_data.py
"""
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DECK = ROOT / 'deck'
RAW, RES = ROOT / 'raw', ROOT / 'results'
MARK_A, MARK_B = '# --- BEGIN INLINE DATA (generated by prep_data.py; do not edit) ---', '# --- END INLINE DATA ---'

R = pd.read_stata(next(p for p in [RAW / 'aging_growth_data.dta', RAW / 'AGING_GROWTH.dta'] if p.exists()))
R['name'] = R.cname_ifr.str.strip()
OECD = set(R.loc[R.sample_oecd == 1, 'countrycode'])


def r3(x):
    return None if x is None or (isinstance(x, float) and not np.isfinite(x)) else round(float(x), 4)


# ---- Figure 1: unweighted mean of old/young across the 169 countries (reproduces the paper's figure)
def fig1():
    rows = []
    for y in range(1950, 2055, 5):
        for g, m in [('All countries', R.index == R.index), ('OECD', R.sample_oecd == 1)]:
            rows.append(dict(year=y, group=g, vintage='UN WPP 2015 (paper)', value=r3(R.loc[m, f'dependency_50_y{y}'].mean()),
                             phase='projection' if y > 2015 else 'estimate'))
    p = pd.read_csv(RAW / 'WPP2024_Population1JanuaryByAge5GroupSex_Medium.csv.gz',
                    usecols=['ISO3_code', 'Time', 'AgeGrpStart', 'PopTotal'], low_memory=False)
    p = p[p.ISO3_code.isin(set(R.countrycode)) & p.Time.between(1950, 2050)]
    old = p[p.AgeGrpStart >= 50].groupby(['ISO3_code', 'Time']).PopTotal.sum()
    yng = p[p.AgeGrpStart.between(20, 45)].groupby(['ISO3_code', 'Time']).PopTotal.sum()
    dep = (old / yng).rename('dep').reset_index()
    for y, s in dep.groupby('Time'):
        for g, m in [('All countries', s.ISO3_code.notna()), ('OECD', s.ISO3_code.isin(OECD))]:
            rows.append(dict(year=int(y), group=g, vintage='UN WPP 2024', value=r3(s.loc[m, 'dep'].mean()),
                             phase='projection' if y > 2023 else 'estimate'))
    return rows


# ---- Figure 2: change in old/young vs change in log GDP per capita, paper data and new data
def fig2():
    b = pd.read_pickle(ROOT / 'build' / 'pwt11.pkl').set_index(['countrycode', 'year'])
    a = pd.read_pickle(ROOT / 'build' / 'wpp_age.pkl').set_index(['ISO3_code', 'Time']).dep50
    rows = []
    for _, c in R.iterrows():
        k = c.countrycode
        new_dy = np.log(b.loc[(k, 2023), 'rgdpna'] / b.loc[(k, 2023), 'pop']) - np.log(b.loc[(k, 1990), 'rgdpna'] / b.loc[(k, 1990), 'pop'])
        rows.append(dict(iso=k, name=c['name'], oecd=int(c.sample_oecd == 1),
                         x_paper=r3(c.dependency_50_y2015 - c.dependency_50_y1990),
                         y_paper=r3(np.log(c.rgdpna2014 / c.pop2014) - np.log(c.rgdpna1990 / c.pop1990)),
                         x_new=r3(a[(k, 2023)] - a[(k, 1990)]), y_new=r3(new_dy)))
    return rows


def fig3():
    d = pd.read_csv(RES / 'fig3_robots_digitized.csv')
    names = R.set_index('countrycode').name
    return [dict(iso=r.iso, name=names.get(r.iso, r.iso), oecd=int(r.oecd), x=r3(r.aging_data), y=r3(r.robots_change))
            for r in d.itertuples()]


def replication():
    d = pd.read_csv(RES / 'replication_results.csv')
    d['panel'] = d.panel.fillna('')
    keep = ['table', 'panel', 'col', 'b', 'se', 'N', 'F', 'J_p', 'b_paper', 'se_paper', 'F_paper', 'J_p_paper', 'match']
    return [{k: (r3(v) if isinstance(v, float) else (v.item() if hasattr(v, 'item') else v)) for k, v in row.items()}
            for row in d[keep].to_dict('records')]


RUN_LABEL = {('B0 original data', 'original'): 'Original (PWT 9, UN 2015)',
             ('B1 PWT 11 only', 'original'): 'Swap GDP → PWT 11',
             ('B2 WPP 2024 only', 'original'): 'Swap aging → WPP 2024',
             ('B3 PWT 11 + WPP 2024', 'original'): 'Both new, same window',
             ('E2019', 'original'): '1990–2019',
             ('E2019', 'shifted'): '1990–2019, shifted IVs',
             ('E2023', 'original'): '1990–2023',
             ('E2023', 'shifted'): '1990–2023, shifted IVs'}


def extension():
    d = pd.read_csv(RES / 'extension_results.csv')
    d['panel'] = d.panel.fillna('')
    d['inst'] = np.where(d.instruments.str.startswith('shifted'), 'shifted', 'original')
    d['label'] = [RUN_LABEL[(r, i)] for r, i in zip(d.run, d.inst)]
    d['order'] = [list(RUN_LABEL).index((r, i)) for r, i in zip(d.run, d.inst)]
    cols = ['table', 'panel', 'col', 'label', 'order', 'b', 'se', 'N', 'F', 'J_p', 'AR_lo', 'AR_hi', 'AR_status',
            'b_ji', 'se_ji', 'F_ji', 'AR_ji_lo', 'AR_ji_hi', 'AR_ji_status', 'windows']
    out = []
    for row in d[cols].to_dict('records'):
        out.append({k: (r3(v) if isinstance(v, float) else (None if v is None else (v.item() if hasattr(v, 'item') else v)))
                    for k, v in row.items()})
    return out


def main():
    data = dict(fig1=fig1(), fig2=fig2(), fig3=fig3(), replication=replication(), extension=extension())
    js = json.dumps(data, separators=(',', ':'), allow_nan=False)
    (DECK / 'public').mkdir(exist_ok=True)
    (DECK / 'public' / 'deck_data.json').write_text(js)
    nb = DECK / 'deck.py'
    if nb.exists():
        src = nb.read_text()
        block = f"{MARK_A}\n    DATA_JSON = r'''{js}'''\n    {MARK_B}"
        new, n = re.subn(re.escape(MARK_A) + r'.*?' + re.escape(MARK_B), lambda _: block, src, flags=re.S)
        assert n == 1, 'inline-data markers not found exactly once in deck.py'
        nb.write_text(new)
    print({k: len(v) for k, v in data.items()}, f'{len(js) / 1024:.0f} KB')


if __name__ == '__main__':
    main()
